//! Golden-vector emitter for the demo tier. Deterministic; the output is the contract with the POS.
use super::{journal, record};
use std::fmt::Write as _;

fn hx(b: &[u8]) -> String { hex::encode(b) }

pub fn emit() -> String {
    let key: [u8; 16] = core::array::from_fn(|i| i as u8);
    let uid: [u8; 7] = [0x04, 0x95, 0x8C, 0xAA, 0x5C, 0x5E, 0x80];
    let uid_other: [u8; 7] = [0x04, 0xEB, 0xBB, 0x02, 0xCD, 0x2A, 0x81];
    let reserve_id: [u8; 32] = core::array::from_fn(|i| 0xA0 + i as u8);
    let merchant_id: [u8; 8] = [0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88];
    let mut s = String::new();
    writeln!(s, "# prepaid demo tier golden vectors v1 (generated by rust-core: cargo run --example emit_prepaid_vectors -- tests/fixtures/prepaid_demo_vectors.txt)").unwrap();
    writeln!(s, "k_debit={}", hx(&key)).unwrap();
    writeln!(s, "uid={}", hx(&uid)).unwrap();
    writeln!(s, "uid_other={}", hx(&uid_other)).unwrap();
    let rfc_key: [u8; 16] = hex::decode("2b7e151628aed2a6abf7158809cf4f3c").unwrap().try_into().unwrap();
    writeln!(s, "cmac.rfc4493.m16={}", hx(&super::cmac::aes_cmac(&rfc_key, &hex::decode("6bc1bee22e409f96e93d7e117393172a").unwrap()))).unwrap();
    let t7: [u8; 16] = hex::decode("B565AC978FA46D5784C845CD1444102C").unwrap().try_into().unwrap();
    writeln!(s, "cmac8.table7={}", hx(&super::cmac::mac_truncate(&t7))).unwrap();

    let mk = |counter: u32, balance: i32| record::DemoCardRecord {
        version: record::VERSION_DEMO, scheme: record::SCHEME_CKB_MILLI, writer_id: 3, reserve_id,
        balance_units: balance, counter, merchant_id, mac: [0; 8] };
    let mut raws = Vec::new();
    for (i, (c, b)) in [(5u32, 1_000_000i32), (6, 998_500), (5, 1)].iter().enumerate() {
        let mut r = mk(*c, *b);
        let raw = record::seal(&key, &uid, &mut r);
        let n = i + 1;
        writeln!(s, "record{n}.writer_id={}", r.writer_id).unwrap();
        writeln!(s, "record{n}.reserve_id={}", hx(&r.reserve_id)).unwrap();
        writeln!(s, "record{n}.balance_units={}", r.balance_units).unwrap();
        writeln!(s, "record{n}.counter={}", r.counter).unwrap();
        writeln!(s, "record{n}.merchant_id={}", hx(&r.merchant_id)).unwrap();
        writeln!(s, "record{n}.raw={}", hx(&raw)).unwrap();
        writeln!(s, "record{n}.mac8={}", hx(&r.mac)).unwrap();
        raws.push(raw);
    }
    let zeros = [0u8; 64];
    let mut bad = raws[1]; bad[60] ^= 0xFF;
    let uid_other_raw = { let mut r = mk(6, 998_500); record::seal(&key, &uid_other, &mut r) };
    let cases: [(&[u8; 64], &[u8; 64], &str); 8] = [
        (&raws[0], &raws[1], "B"), (&zeros, &bad, "NONE"), (&raws[0], &raws[2], "AMBIGUOUS"), (&raws[0], &raws[0], "A"),
        (&raws[1], &raws[0], "A"), (&raws[0], &bad, "A"), (&bad, &raws[0], "B"), (&uid_other_raw, &raws[0], "B")];
    for (i, (a, b, pick)) in cases.iter().enumerate() {
        let n = i + 1;
        // sanity: the emitter's own select_slot must agree with the labelled pick
        let got = record::select_slot(&key, &uid, a, b).0;
        let want = match *pick { "A" => record::SlotPick::A, "B" => record::SlotPick::B, "NONE" => record::SlotPick::None, _ => record::SlotPick::Ambiguous };
        assert_eq!(got, want, "emitter self-check slots.case{n}");
        writeln!(s, "slots.case{n}.a={}", hx(*a)).unwrap();
        writeln!(s, "slots.case{n}.b={}", hx(*b)).unwrap();
        writeln!(s, "slots.case{n}.pick={pick}").unwrap();
    }
    let mk_e = |kind: u8, tmc: u32, amount: i32, after: i32| journal::JournalEntry {
        version: journal::VERSION_DEMO, kind, terminal_id: 3, merchant_id, uid, reserve_id, tmc,
        amount_units: amount, balance_after: after, ts: 1_791_370_000, tmv: [0; 8],
        sale_ref: [0xDE, 0xAD, 0xBE, 0xEF, 0x01, 0x02, 0x03, 0x04] };
    for (i, mut e) in [mk_e(journal::KIND_DEBIT, 6, 1500, 998_500), mk_e(journal::KIND_REFUND, 7, -300, 998_800)].into_iter().enumerate() {
        let raw = journal::attest(&key, &mut e);
        let n = i + 1;
        writeln!(s, "entry{n}.kind={}", e.kind).unwrap();
        writeln!(s, "entry{n}.terminal_id={}", e.terminal_id).unwrap();
        writeln!(s, "entry{n}.merchant_id={}", hx(&e.merchant_id)).unwrap();
        writeln!(s, "entry{n}.uid={}", hx(&e.uid)).unwrap();
        writeln!(s, "entry{n}.reserve_id={}", hx(&e.reserve_id)).unwrap();
        writeln!(s, "entry{n}.tmc={}", e.tmc).unwrap();
        writeln!(s, "entry{n}.amount_units={}", e.amount_units).unwrap();
        writeln!(s, "entry{n}.balance_after={}", e.balance_after).unwrap();
        writeln!(s, "entry{n}.ts={}", e.ts).unwrap();
        writeln!(s, "entry{n}.sale_ref={}", hx(&e.sale_ref)).unwrap();
        writeln!(s, "entry{n}.raw={}", hx(&raw)).unwrap();
        writeln!(s, "entry{n}.tmv={}", hx(&e.tmv)).unwrap();
    }
    s
}
